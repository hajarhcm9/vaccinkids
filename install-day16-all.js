// EXECUTION
// =============================================

console.log('=== VacciniKids Day 16 - Self-Contained Installer ===\n');

var okCount = 0;
var skipCount = 0;
var failCount = 0;

// Step 1: Write new files
console.log('--- Step 1: Creating new files ---');
var fileNames = Object.keys(FILES);
fileNames.forEach(function(relPath) {
  var filePath = path.join(BASE, relPath);
  try {
    var dir = path.dirname(filePath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
      console.log('  Created directory: ' + dir);
    }
    fs.writeFileSync(filePath, FILES[relPath], 'utf8');
    console.log('OK: ' + relPath);
    okCount++;
  } catch (err) {
    console.log('FAIL: ' + relPath + ' -> ' + err.message);
    failCount++;
  }
});

// Step 2: Patch existing files
console.log('\n--- Step 2: Patching existing files ---');
var patches = [
  { path: 'src/utils/responseHandler.js', fn: patchResponseHandler },
  { path: 'src/app.js', fn: patchAppJs },
  { path: 'src/config/index.js', fn: patchConfig },
];

patches.forEach(function(patch) {
  var filePath = path.join(BASE, patch.path);
  try {
    if (!fs.existsSync(filePath)) {
      console.log('SKIP: ' + patch.path + ' does not exist');
      skipCount++;
      return;
    }
    var content = fs.readFileSync(filePath, 'utf8');
    var result = patch.fn(content);
    if (result === null) {
      console.log('SKIP (already patched): ' + patch.path);
      skipCount++;
      return;
    }
    fs.writeFileSync(filePath, result, 'utf8');
    console.log('PATCHED: ' + patch.path);
    okCount++;
  } catch (err) {
    console.log('FAIL: ' + patch.path + ' -> ' + err.message);
    failCount++;
  }
});

console.log('\n=== Result: ' + okCount + ' ok, ' + skipCount + ' skipped, ' + failCount + ' failed ===');
console.log('\nNext steps:');
console.log('1. Run: npx jest emailPdf --no-coverage --verbose');
console.log('2. Run: npx jest --no-coverage --verbose  (full suite)');
