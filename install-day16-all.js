function patchResponseHandler(content) {
  if (content.indexOf('notFound') !== -1 && content.indexOf('error') !== -1 && content.indexOf('module.exports') !== -1 && content.indexOf('notFound') < content.indexOf('module.exports')) {
    return null; // already patched
  }
  var addition = '\n'
    + '/**\n'
    + ' * Not found response (404)\n'
    + ' */\n'
    + 'var notFound = function(res, message) {\n'
    + "  return res.status(404).json({ status: 'error', message: message || 'Resource not found' });\n"
    + '};\n'
    + '\n'
    + '/**\n'
    + ' * Error response\n'
    + ' */\n'
    + 'var error = function(res, message, statusCode) {\n'
    + "  return res.status(statusCode || 500).json({ status: 'error', message: message || 'Internal Server Error' });\n"
    + '};\n'
    + '\n';

  content = content.replace(
    'module.exports = { success, created, noContent, paginated };',
    addition + 'module.exports = { success, created, noContent, paginated, notFound, error };'
  );
  return content;
}

function patchAppJs(content) {
  if (content.indexOf('emailRoutes') !== -1 && content.indexOf('pdfRoutes') !== -1) {
    return null; // already patched
  }
  var routeLines = "app.use('/api/emails', require('./routes/emailRoutes'));\n"
    + "app.use('/api/pdf', require('./routes/pdfRoutes'));\n";

  if (content.indexOf('// 404') !== -1) {
    content = content.replace('// 404', '// Day 16 - Email & PDF Routes\n' + routeLines + '\n// 404');
  } else if (content.indexOf('app.use((req, res)') !== -1) {
    content = content.replace('app.use((req, res)', '// Day 16 - Email & PDF Routes\n' + routeLines + '\napp.use((req, res)');
  } else {
    console.log('  WARNING: Could not find insertion point in app.js');
    return null;
  }
  return content;
}

function patchConfig(content) {
  if (content.indexOf('email:') !== -1 && content.indexOf('EMAIL_HOST') !== -1) {
    return null; // already patched
  }
  // Add isTest
  if (content.indexOf('isTest') === -1) {
    content = content.replace(
      "isProd: process.env.NODE_ENV === 'production',",
      "isProd: process.env.NODE_ENV === 'production',\n  isTest: process.env.NODE_ENV === 'test',"
    );
  }
  // Add email config
  var emailConfig = '\n'
    + '  // Email\n'
    + '  email: {\n'
    + "    host: process.env.EMAIL_HOST || 'smtp.ethereal.email',\n"
    + '    port: parseInt(process.env.EMAIL_PORT, 10) || 587,\n'
    + "    secure: process.env.EMAIL_SECURE === 'true',\n"
    + "    user: process.env.EMAIL_USER || '',\n"
    + "    password: process.env.EMAIL_PASSWORD || '',\n"
    + "    from: process.env.EMAIL_FROM || '\"VacciniKids\" <noreply@vaccinikids.ma>',\n"
    + '  },\n';

  if (content.indexOf('// Firebase') !== -1) {
    content = content.replace('// Firebase', emailConfig + '  // Firebase');
  } else {
    console.log('  WARNING: Could not find Firebase section in config');
    return null;
  }
  return content;
}

