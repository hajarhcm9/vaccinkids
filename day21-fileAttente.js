var fs = require('fs');
var path = require('path');
var execSync = require('child_process').execSync;

var BASE = process.cwd();

function writeFile(relPath, content) {
  var fullPath = path.join(BASE, relPath);
  fs.writeFileSync(fullPath, content, 'utf8');
  try {
    execSync('node -c ' + fullPath, { encoding: 'utf8' });
    console.log('  [WRITE OK] ' + relPath + ' (' + content.length + ' bytes)');
  } catch (e) {
    console.log('  [WRITE ERROR] ' + relPath + ' SYNTAX ERROR: ' + e.message);
  }
}

function readFile(relPath) {
  var fullPath = path.join(BASE, relPath);
  try { return fs.readFileSync(fullPath, 'utf8'); }
  catch (e) { return null; }
}

function runCmd(cmd) {
  try { return execSync(cmd, { encoding: 'utf8', timeout: 120000, cwd: BASE }); }
  catch (e) { return e.stdout || e.message; }
}

